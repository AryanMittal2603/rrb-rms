// Printable letters (call letters, memos, offers, dossiers) on an RRB letterhead.
import { h, icon } from '../core/h.js';
import { modal } from './dialogs.js';
import { L } from '../i18n.js';
import { isPublic } from '../core/env.js';

function brandSrc(sel) {
  const img = document.querySelector(sel);
  return img ? img.getAttribute('src') : '';
}

export function letterhead(office, ref, dateText) {
  if (isPublic()) {
    return h('header.rms-doc__head',
      h('span.rms-doc__mark', 'RMS'),
      h('div.rms-doc__office',
        h('p.rms-doc__en', L('doc.specimenLine', 'Specimen generated by the RMS product demo')),
        h('p.rms-doc__org', office || ''),
        h('p.rms-doc__en', L('doc.notOfficial', 'Not an official document'))),
      h('span.rms-doc__mark.rms-doc__mark--demo', 'DEMO'),
      ref || dateText ? h('div.rms-doc__ref', ref ? h('span', L('doc.ref', 'No.') + ' ' + ref) : null, dateText ? h('span', L('doc.date', 'Date') + ': ' + dateText) : null) : null);
  }
  return h('header.rms-doc__head',
    h('img.rms-doc__emblem', { src: brandSrc('.masthead__emblem img'), alt: '', width: 40, height: 66 }),
    h('div.rms-doc__office',
      h('p.rms-doc__hi', 'भारत सरकार · रेल मंत्रालय'),
      h('p.rms-doc__en', 'Government of India · Ministry of Railways'),
      h('p.rms-doc__org', office || 'Railway Recruitment Board, Bengaluru')),
    h('img.rms-doc__logo', { src: brandSrc('.masthead__logo img'), alt: '', width: 64, height: 64 }),
    ref || dateText ? h('div.rms-doc__ref', ref ? h('span', L('doc.ref', 'No.') + ' ' + ref) : null, dateText ? h('span', L('doc.date', 'Date') + ': ' + dateText) : null) : null);
}

export function docShell(o) {
  return h('article.rms-doc' + (isPublic() ? '.rms-doc--specimen' : '') + (o.cls ? '.' + o.cls : ''),
    letterhead(o.office, o.ref, o.date),
    o.title ? h('h2.rms-doc__title', o.title) : null,
    o.body,
    o.watermark !== false ? h('p.rms-doc__demo', L('doc.demo', 'Demo document — generated from synthetic data, not valid for any purpose.')) : null);
}

export function showDoc(o) {
  const doc = docShell(o);
  return modal({
    title: o.dialogTitle || o.title,
    body: doc,
    actions: [
      { label: L('ui.print', 'Print'), onClick: () => { printNode(doc); return false; } },
      o.extra ? o.extra : null,
      { label: L('ui.close', 'Close'), kind: 'plain', value: false },
    ].filter(Boolean),
  });
}

export function printNode(node) {
  node.classList.add('rms-print-target');
  document.body.classList.add('rms-printing');
  const done = () => {
    document.body.classList.remove('rms-printing');
    node.classList.remove('rms-print-target');
    window.removeEventListener('afterprint', done);
  };
  window.addEventListener('afterprint', done);
  window.print();
  setTimeout(done, 1500);
}

export function sigBlock(name, title) {
  return h('div.rms-doc__sign', h('div.rms-doc__esign', icon('shield', 14), h('span', isPublic() ? L('doc.specimenSign', 'Specimen signature (demo)') : L('doc.esigned', 'Digitally signed (demo)'))), h('p', h('strong', name)), h('p', title));
}
